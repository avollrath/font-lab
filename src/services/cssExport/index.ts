import type { TypographyRule } from '../../types';

function collectFontFamilies(rules: TypographyRule[]): string[] {
  const families: Set<string> = new Set();
  for (const rule of rules) {
    if (rule.enabled && rule.fontFamily?.enabled && rule.fontFamily.value) {
      families.add(rule.fontFamily.value);
    }
  }
  return Array.from(families);
}

function collectWeightsForFamily(family: string, rules: TypographyRule[]): number[] {
  const weights: Set<number> = new Set([400]);
  for (const rule of rules) {
    if (
      rule.enabled &&
      rule.fontFamily?.enabled &&
      rule.fontFamily.value === family &&
      rule.fontWeight?.enabled &&
      rule.fontWeight.value
    ) {
      weights.add(rule.fontWeight.value);
    }
  }
  return Array.from(weights).sort((a, b) => a - b);
}

function generateImports(rules: TypographyRule[]): string {
  const families = collectFontFamilies(rules);
  if (families.length === 0) return '';

  const params = families.map(family => {
    const weights = collectWeightsForFamily(family, rules);
    const encoded = encodeURIComponent(family);
    return `family=${encoded}:wght@${weights.join(';')}`;
  }).join('&');

  return `@import url("https://fonts.googleapis.com/css2?${params}&display=swap");\n\n`;
}

function generateRuleExportCSS(rule: TypographyRule, includeImportant: boolean): string {
  const bang = includeImportant ? ' !important' : '';
  const declarations: string[] = [];

  if (rule.fontFamily?.enabled && rule.fontFamily.value) {
    declarations.push(`  font-family: "${rule.fontFamily.value}", Arial, sans-serif${bang}`);
  }
  if (rule.fontSize?.enabled && rule.fontSize.value) {
    const { value, unit } = rule.fontSize.value;
    if (value > 0) declarations.push(`  font-size: ${value}${unit}${bang}`);
  }
  if (rule.fontWeight?.enabled && rule.fontWeight.value) {
    declarations.push(`  font-weight: ${rule.fontWeight.value}${bang}`);
  }
  if (rule.lineHeight?.enabled && rule.lineHeight.value) {
    declarations.push(`  line-height: ${rule.lineHeight.value}${bang}`);
  }
  if (rule.letterSpacing?.enabled && rule.letterSpacing.value !== undefined) {
    declarations.push(`  letter-spacing: ${rule.letterSpacing.value}${bang}`);
  }
  if (rule.fontStyle?.enabled && rule.fontStyle.value) {
    declarations.push(`  font-style: ${rule.fontStyle.value}${bang}`);
  }
  if (rule.textTransform?.enabled && rule.textTransform.value) {
    declarations.push(`  text-transform: ${rule.textTransform.value}${bang}`);
  }

  if (declarations.length === 0) return '';
  return `${rule.selector} {\n${declarations.join(';\n')};\n}\n`;
}

export function exportCSS(rules: TypographyRule[], includeImportant = false): string {
  const activeRules = rules.filter(r => r.enabled);
  if (activeRules.length === 0) return '/* No active typography rules */\n';

  const imports = generateImports(activeRules);
  const body = activeRules
    .map(r => generateRuleExportCSS(r, includeImportant))
    .filter(Boolean)
    .join('\n');

  return `/* Generated by Font Lab */\n\n${imports}${body}`;
}
