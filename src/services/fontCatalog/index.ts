export function searchFonts(query: string, category?: string): FontCatalogEntry[] {
  const q = query.toLowerCase().trim();
  return FONT_CATALOG.filter(f => {
    const matchesQuery = !q || f.family.toLowerCase().includes(q);
    const matchesCategory = !category || f.category === category;
    return matchesQuery && matchesCategory;
  });
}

export function getFontByName(family: string): FontCatalogEntry | undefined {
  return FONT_CATALOG.find(f => f.family === family);
}
